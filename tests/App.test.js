import { mount, flushPromises } from '@vue/test-utils'
import { beforeEach, expect, it, vi } from 'vitest'
import App from '../src/App.vue'
const response = data => Promise.resolve({ ok: true, json: async () => data })
beforeEach(() => { localStorage.clear(); vi.restoreAllMocks() })
it('loads API tasks, updates completion, and filters tasks', async () => {
  const fetch = vi.fn().mockImplementationOnce(() => response({ todos: [{ id: 1, todo: 'Read a book', completed: false, userId: 1 }] })).mockImplementationOnce(() => response({ completed: true }))
  vi.stubGlobal('fetch', fetch)
  const wrapper = mount(App); await flushPromises()
  expect(fetch.mock.calls[0][0]).toBe('https://dummyjson.com/todos/user/1')
  await wrapper.get('input[type=checkbox]').setValue(true); await flushPromises()
  expect(JSON.parse(fetch.mock.calls[1][1].body)).toEqual({ completed: true })
  expect(wrapper.text()).toContain('1 of 1 tasks completed')
  await wrapper.findAll('.tabs button')[1].trigger('click')
  expect(wrapper.findAll('.task-list li')).toHaveLength(0)
  wrapper.unmount()
})
it('adds multiple tasks with unique IDs and restores browser changes', async () => {
  localStorage.setItem('daily-todos-v1', '[]')
  const fetch = vi.fn(() => response({ id: 255, userId: 1 }))
  vi.stubGlobal('fetch', fetch)
  const wrapper = mount(App); await flushPromises()
  for (const title of ['Buy milk', 'Walk dog']) {
    await wrapper.get('#task').setValue(title)
    await wrapper.get('form').trigger('submit'); await flushPromises()
  }
  expect(wrapper.findAll('.task-list li')).toHaveLength(2)
  expect(JSON.parse(localStorage.getItem('daily-todos-v1')).map(t => t.id)[0]).not.toBe(JSON.parse(localStorage.getItem('daily-todos-v1'))[1].id)
  await wrapper.get('input[type=checkbox]').setValue(true); await flushPromises()
  expect(fetch).toHaveBeenCalledTimes(2)
  wrapper.unmount()
  const restored = mount(App); await flushPromises()
  expect(restored.text()).toContain('Walk dog')
  expect(restored.text()).toContain('1 of 2 tasks completed')
  restored.unmount()
})
it('preserves text after failed creation and keeps failed updates unchanged', async () => {
  localStorage.setItem('daily-todos-v1', JSON.stringify([{ id: 1, todo: 'Existing task', completed: false }]))
  vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('Offline')))
  const wrapper = mount(App); await flushPromises()
  await wrapper.get('#task').setValue('Keep this text')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(wrapper.get('#task').element.value).toBe('Keep this text')
  expect(wrapper.get('[role=alert]').text()).toContain('Could not add')
  await wrapper.get('input[type=checkbox]').setValue(true); await flushPromises()
  expect(wrapper.text()).toContain('0 of 1 tasks completed')
  wrapper.unmount()
})
it('shows a retry when initial loading fails', async () => {
  vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('Offline')))
  const wrapper = mount(App); await flushPromises()
  expect(wrapper.get('[role=alert]').text()).toContain('Could not load')
  expect(wrapper.get('[role=alert] button').text()).toBe('Try again')
  wrapper.unmount()
})
